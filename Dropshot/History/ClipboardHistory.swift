import AppKit
import ImageIO
import Observation

/// One remembered clipboard entry.
struct ClipItem: Identifiable {
    enum Content {
        case text(String)
        /// Image copied as raw data (no file behind it).
        case image(Data, NSPasteboard.PasteboardType)
        case files([URL])
    }

    let id = UUID()
    let content: Content
    let thumbnail: NSImage?
    let date: Date
    /// Used to recognise the same thing being copied again.
    let signature: String

    var title: String {
        switch content {
        case .text(let string):
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            return trimmed.isEmpty ? "(whitespace)" : String(trimmed.prefix(200))
        case .image: return "Image"
        case .files(let urls):
            guard let first = urls.first else { return "File" }
            return urls.count == 1 ? first.lastPathComponent : "\(first.lastPathComponent) + \(urls.count - 1) more"
        }
    }

    var subtitle: String {
        switch content {
        case .text(let string): return "\(string.count) characters"
        case .image(let data, _):
            return ByteCountFormatter.string(fromByteCount: Int64(data.count), countStyle: .file)
        case .files(let urls): return urls.count == 1 ? "File" : "\(urls.count) files"
        }
    }

    var symbol: String {
        switch content {
        case .text: "text.alignleft"
        case .image: "photo"
        case .files: "doc"
        }
    }
}

/// Clipboard history (the ⌘⇧V panel). Kept in memory only — nothing is written to disk and
/// it is gone when Dropshot quits. Entries marked as concealed or transient by the source
/// app (password managers) are never recorded.
@MainActor
@Observable
final class ClipboardHistory {
    static let maxItems = 30
    private static let maxImageBytes = 8 * 1024 * 1024
    private static let maxImageItems = 6
    private static let maxTextLength = 100_000

    private(set) var items: [ClipItem] = []

    @ObservationIgnored private let pasteboard = NSPasteboard.general
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var timer: Timer?

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        // The pasteboard has no change notification; comparing an integer twice a second
        // is what every clipboard manager does and costs nothing measurable.
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func clear() {
        items.removeAll()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard let item = read() else { return }
        items.removeAll { $0.signature == item.signature }
        items.insert(item, at: 0)
        trim()
    }

    private func trim() {
        if items.count > Self.maxItems {
            items.removeLast(items.count - Self.maxItems)
        }
        // Raw image data is the only heavy thing we hold; keep just the newest few.
        var images = 0
        items.removeAll { item in
            guard case .image = item.content else { return false }
            images += 1
            return images > Self.maxImageItems
        }
    }

    private func read() -> ClipItem? {
        let types = pasteboard.types ?? []
        let secret: Set<String> = [
            "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        ]
        guard !types.contains(where: { secret.contains($0.rawValue) }) else { return nil }

        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipItem(
                content: .files(urls),
                thumbnail: urls.first.flatMap(Self.thumbnail(forFile:)),
                date: Date(),
                signature: "files:" + urls.map(\.path).joined(separator: "|"))
        }

        if let string = pasteboard.string(forType: .string), !string.isEmpty {
            guard string.count <= Self.maxTextLength else { return nil }
            return ClipItem(content: .text(string), thumbnail: nil, date: Date(), signature: "text:" + string)
        }

        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            guard let data = pasteboard.data(forType: type), data.count <= Self.maxImageBytes else { continue }
            return ClipItem(
                content: .image(data, type),
                thumbnail: Self.thumbnail(forImageData: data),
                date: Date(),
                signature: "image:\(data.count):\(data.prefix(4096).hashValue)")
        }
        return nil
    }

    /// Puts `item` back on the clipboard (and moves it to the top of the history).
    func copy(_ item: ClipItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let string):
            pasteboard.setString(string, forType: .string)
        case .image(let data, let type):
            pasteboard.setData(data, forType: type)
        case .files(let urls):
            let existing = urls.filter { FileManager.default.fileExists(atPath: $0.path) }
            if existing.count == 1, let url = existing.first, Self.isImage(url),
               let data = try? Data(contentsOf: url, options: .mappedIfSafe),
               data.count <= 32 * 1024 * 1024 {
                // Same shape as a fresh screenshot: image data and the file together.
                let entry = NSPasteboardItem()
                let type: NSPasteboard.PasteboardType = url.pathExtension.lowercased() == "png"
                    ? .png : NSPasteboard.PasteboardType("public.\(url.pathExtension.lowercased())")
                entry.setData(data, forType: type)
                entry.setString(url.absoluteString, forType: .fileURL)
                pasteboard.writeObjects([entry])
            } else {
                pasteboard.writeObjects(existing.map { $0 as NSURL })
            }
        }
        lastChangeCount = pasteboard.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(item, at: 0)
    }

    // MARK: Thumbnails

    private static func isImage(_ url: URL) -> Bool {
        ["png", "jpg", "jpeg", "heic", "tiff", "gif"].contains(url.pathExtension.lowercased())
    }

    private static func thumbnail(forFile url: URL) -> NSImage? {
        guard isImage(url), let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        return thumbnail(from: source)
    }

    private static func thumbnail(forImageData data: Data) -> NSImage? {
        guard let source = CGImageSourceCreateWithData(data as CFData, nil) else { return nil }
        return thumbnail(from: source)
    }

    private static func thumbnail(from source: CGImageSource) -> NSImage? {
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: 160,
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return nil }
        return NSImage(cgImage: image, size: NSSize(width: image.width / 2, height: image.height / 2))
    }
}
